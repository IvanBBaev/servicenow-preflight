#!/usr/bin/env node
// Generate site/checks.generated.js — the docs site's check catalogue — from
// the check registry, so the Pages board can never drift from the code.
//
//   node scripts/gen-site.mjs             write the file
//   node scripts/gen-site.mjs --check     exit 1 if the committed file is stale
//   --out <path>                          target another file (tests)
//
// Reads ../build/index.js, so run `npm run build` first.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_OUT = join(ROOT, "site", "checks.generated.js");

/**
 * Map check descriptors (from `describeChecks`) to the entries the site board
 * renders: `code` is the two-digit gate number (position in the suite), `tag`
 * the check's `meta.requires`, `desc` its `meta.summary` or `description`.
 */
export function toSiteEntries(descriptors) {
  return descriptors.map((d, i) => ({
    code: String(i + 1).padStart(2, "0"),
    name: d.name,
    tag: d.meta.requires ?? "",
    desc: d.meta.summary ?? d.description,
    fail: d.meta.verdicts?.fail ?? "",
    warn: d.meta.verdicts?.warn ?? "",
    pass: d.meta.verdicts?.pass ?? "",
  }));
}

/** Render the descriptor list as the browser script the page loads. */
export function renderSiteCatalogue(descriptors) {
  return (
    "// Generated by scripts/gen-site.mjs from the check registry — do not edit.\n" +
    "// Regenerate with `npm run gen:site`; `npm run check` fails when stale.\n" +
    "window.PREFLIGHT_CHECKS = " +
    JSON.stringify(toSiteEntries(descriptors), null, 2) +
    ";\n"
  );
}

async function main(argv) {
  const check = argv.includes("--check");
  const outIdx = argv.indexOf("--out");
  const out = outIdx >= 0 ? argv[outIdx + 1] : DEFAULT_OUT;
  if (!out) throw new Error("--out needs a path");

  const lib = await import(pathToFileURL(join(ROOT, "build", "index.js")).href);
  const content = renderSiteCatalogue(lib.describeChecks(lib.defaultChecks));
  const shown = relative(process.cwd(), out) || out;

  if (!check) {
    writeFileSync(out, content);
    console.log(`gen-site: wrote ${shown}`);
    return 0;
  }
  let current = null;
  try {
    current = readFileSync(out, "utf8");
  } catch {
    // missing file is reported as stale below
  }
  if (current === content) {
    console.log(`gen-site: ${shown} is up to date`);
    return 0;
  }
  console.error(
    `gen-site: ${shown} is out of date with the check registry.\n` +
      "  Run `npm run build && npm run gen:site` and commit the result.",
  );
  return 1;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  main(process.argv.slice(2)).then(
    (code) => process.exit(code),
    (err) => {
      console.error(`gen-site: ${err.message}`);
      process.exit(2);
    },
  );
}
